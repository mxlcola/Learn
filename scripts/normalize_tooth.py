LINK_RE = re.compile(r'\[\[([^\]|]+)(?:\|[^\]]*)?\]\]')
REL_HEAD_RE = re.compile(r'^关联[：:]')
LINK_LINE_RE = re.compile(r'^(?:\[\[[^\]]+\]\]\s*[、，,]?\s*)+$')


# 标签为空但属于本域的关键条目（域内总纲/枢纽卡）
EXTRA = {'种牙', '牙周炎', '龋齿', '上颌窦提升', '慢性根尖周炎', '上颌窦', '种植体'}


def norm_key(s):
    """忽略引号、空白差异，用于标题匹配。"""
    s = re.sub(r'["“”\']', '', s)
    return re.sub(r'\s+', '', s)


def parse(raw):
    nl = '\r\n' if '\r\n' in raw else '\n'
    m = re.search(r'\r?\n\r?\n', raw)
    if not m:
        return nl, raw, ''
    return nl, raw[:m.start()], raw[m.end():]


def normalize_relations(body, extra_links=None, force_links=None):
    """摘掉 关联 块（无论它出现在哪），只在正文没覆盖到的关系上重建。

    原则：正文内联双链已经表达过的关系不再在末行重复；
    末行只留正文没有提到、但确实需要补一条通路的条目，数量按需，可以没有。
    """
    body = body.replace('\r\n', '\n')
    lines = body.split('\n')
    old_links, kept = [], []

    i = 0
    while i < len(lines):
        if REL_HEAD_RE.match(lines[i]):
            j = i + 1
            while j < len(lines) and (not lines[j].strip() or LINK_LINE_RE.match(lines[j].strip())):
                j += 1
            block = '\n'.join(lines[i:j])
            old_links.extend(LINK_RE.findall(block))
            lines = lines[:i] + lines[j:]
            i = i
            continue
        i += 1

    text = re.sub(r'\n{3,}', '\n\n', '\n'.join(lines)).strip('\n')
    inline = set(LINK_RE.findall(text))

    for l in (extra_links or []):
        if l not in inline:
            old_links.append(l)

    if force_links is not None:
        kept = [l for l in force_links if l not in inline]
    else:
        for l in old_links:
            if l not in inline and l not in kept:
                kept.append(l)

    if not kept:
        return text
    rel = '关联：' + '、'.join('[[' + l + ']]' for l in kept)
    return text + '\n\n' + rel


def main(dry=False):
    files = {}
    for fn in os.listdir(TIDDLER_DIR):
        if not fn.endswith('.tid') or fn.startswith('$'):
            continue
        path = os.path.join(TIDDLER_DIR, fn)
        raw = open(path, 'rb').read().decode('utf-8')
        m = re.match(r'(.*?)\r?\n\r?\n', raw, re.S)
        head = m.group(1) if m else raw
        h = head.replace('\r\n', '\n')
        tm = re.search(r'(?m)^title:[ \t]*([^\n]*)$', h)
        title = tm.group(1).strip() if tm else fn[:-4]
        tags = []
        gm = re.search(r'(?m)^tags:[^\n]*$', h)
        if gm:
            tags = [t for t in gm.group(0)[5:].split() if t != '?']
        files[norm_key(title)] = dict(path=path, title=title, raw=raw, tags=tags)

    smap = {norm_key(k): v for k, v in SUMMARY.items()}
    lmap = {norm_key(k): v for k, v in LINKS.items()}
    mmap = {norm_key(k): v for k, v in MANUAL.items()}
    rmap = {norm_key(k): v for k, v in MANUAL_REL.items()}
    existing = set(files)

    missing = [k for k in smap if k not in existing]
    if missing:
        print('!! 概括表里有、库里找不到的标题：')
        for k in missing:
            print('   ', k)

    all_links = set()
    for v in lmap.values():
        all_links.update(v)
    for v in mmap.values():
        all_links.update(LINK_RE.findall(v))
    for v in rmap.values():
        all_links.update(v)
    bad = [l for l in sorted(all_links) if norm_key(l) not in existing]
    if bad:
        print('!! 新造链接指向不存在的条目，已剔除：', bad)

    extra_keys = {norm_key(t) for t in EXTRA}
    changed, skipped = [], []
    for key, f in files.items():
        if not (set(f['tags']) & TOOTH_TAGS) and key not in extra_keys:
            continue
        nl, head, body = parse(f['raw'])
        if key in mmap:
            new_body = mmap[key]
        else:
            body_clean = body.replace('\r\n', '\n')
            has_sum = body_clean.lstrip().startswith('一句话概括')
            if not has_sum:
                if key not in smap:
                    skipped.append((f['title'], '无概括，正文 %.3d 字' % len(body_clean.strip())))
                    continue
                body_clean = '一句话概括：' + smap[key] + '\n\n' + body_clean.lstrip()
            extra = [l for l in lmap.get(key, []) if norm_key(l) in existing]
            force = None
            if key in rmap:
                force = [l for l in rmap[key] if norm_key(l) in existing]
            new_body = normalize_relations(body_clean, extra, force)
        out = head + nl + nl + new_body.strip('\n').replace('\n', nl) + nl
        if out == f['raw']:
            continue
        changed.append((f['title'], len(body), len(new_body)))
        if not dry:
            open(f['path'], 'wb').write(out.encode('utf-8'))

    print('%s处理 %d 张' % ('[预演] ' if dry else '', len(changed)))
    for t, o, n in changed:
        print('   %-28s %4d -> %4d' % (t[:28], o, n))
    if skipped:
        print('\n跳过 %d 张（未写概括，需人工补）：' % len(skipped))
        for t, why in skipped:
            print('   ', t, '|', why)


if __name__ == '__main__':
    main('--dry-run' in sys.argv)
