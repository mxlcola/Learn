def rewrite(title, new_body):
    path = os.path.join(DIR, title + '.tid')
    raw = open(path, 'rb').read().decode('utf-8')
    m = re.search(r'\r?\n\r?\n', raw)
    if not m:
        return None, None
    nl = '\r\n' if '\r\n' in raw[:m.start() + 2] else '\n'
    head, old = raw[:m.start()], raw[m.end():]
    out = head + nl + nl + new_body.strip().replace('\n', nl) + nl
    if DRY:
        return len(old), len(new_body)
    open(path, 'wb').write(out.encode('utf-8'))
    return len(old), len(new_body)


if __name__ == '__main__':
    tot_o = tot_n = 0
    for t, b in BODIES.items():
        o, n = rewrite(t, b)
        if o is None:
            print('跳过(无正文分隔)', t)
            continue
        tot_o += o
        tot_n += n
        print(f'{t:<26} {o:>4} -> {n:>4}')
    print(f'\n合计 {tot_o} -> {tot_n}，压缩 {100*(1-tot_n/tot_o):.0f}%')
