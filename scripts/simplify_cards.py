def parse(raw):
    """按首个空行切分头部与正文，兼容 CRLF / LF / 混合行尾。"""
    nl = '\r\n' if '\r\n' in raw else '\n'
    m = re.search(r'\r?\n\r?\n', raw)
    if not m:
        return nl, raw, ''
    return nl, raw[:m.start()], raw[m.end():]


def normalize_tags(tag_line, keep_prefix):
    """tags: ? 减肥 减脂  ->  tags: ? 减肥"""
    tokens = tag_line[5:].strip().split()
    prefix = []
    out = []
    for t in tokens:
        if t == '?':
            prefix.append(t)
            continue
        if t in DROP_TAGS:
            continue
        t2 = TAG_MAP.get(t, t)
        if t2 not in out:
            out.append(t2)
    ordered = prefix + out
    return 'tags: ' + ' '.join(ordered)


def apply(dry_run=False):
    changed = []
    for title, new_body in CARDS.items():
        path = os.path.join(TIDDLER_DIR, title + '.tid')
        if not os.path.exists(path):
            print('  跳过（不存在）', title)
            continue
        raw = open(path, 'rb').read().decode('utf-8')
        nl, head, old_body = parse(raw)
        # 用 splitlines 兼容混合行尾，输出时统一按 nl 重新拼接
        lines = head.splitlines()
        for i, ln in enumerate(lines):
            if ln.startswith('tags:'):
                lines[i] = normalize_tags(ln, True)
            if ln.startswith('type:') and not ln[5:].strip():
                lines[i] = 'type: text/vnd.tiddlywiki'
        new_head = nl.join(lines)
        body_out = new_body.strip('\n').replace('\n', nl)
        out = new_head + nl + nl + body_out + nl
        if out == raw:
            print('  无变化', title)
            continue
        changed.append((title, len(old_body), len(new_body)))
        if not dry_run:
            open(path, 'wb').write(out.encode('utf-8'))
    print(f'\n{"[预演] " if dry_run else ""}处理 {len(changed)} 张')
    tot_old = sum(c[1] for c in changed)
    tot_new = sum(c[2] for c in changed)
    for t, o, n in changed:
        print(f'  {t}: {o} -> {n}')
    if tot_old:
        print(f'\n合计 {tot_old} -> {tot_new} 字，压缩 {100 * (1 - tot_new / tot_old):.0f}%')


if __name__ == '__main__':
    apply(dry_run='--dry-run' in sys.argv)
