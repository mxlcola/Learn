def parse(raw):
    nl = '\r\n' if '\r\n' in raw else '\n'
    m = re.search(r'\r?\n\r?\n', raw)
    if not m:
        return nl, raw, ''
    return nl, raw[:m.start()], raw[m.end():]


def main(dry):
    titles = {f[:-4] for f in os.listdir(TIDDLER_DIR) if f.endswith('.tid')}
    missing = []
    for t, body in BATCH.items():
        for L in re.findall(r'\[\[([^\]|]+)(?:\|[^\]]*)?\]\]', body):
            if L not in titles and L not in missing:
                missing.append((t, L))
    if missing:
        print('断链警告:')
        for t, L in missing:
            print('  ', t, '->', L)

    rows = []
    for title, body in BATCH.items():
        path = os.path.join(TIDDLER_DIR, title + '.tid')
        if not os.path.exists(path):
            print('跳过（文件不存在）', title)
            continue
        raw = open(path, 'rb').read().decode('utf-8')
        nl, head, old = parse(raw)
        out = head + nl + nl + body.strip('\n').replace('\n', nl) + nl
        rows.append((title, len(old), len(body), out, path))

    over = []
    long1 = []
    for title, old_len, body in [(r[0], r[1], r[2]) for r in rows]:
        txt = BATCH[title]
        first = txt.split('\n')[0]
        s = first[len('一句话概括：'):] if first.startswith('一句话概括：') else ''
        if s and len(s) > 40:
            long1.append((title, len(s), s))
        if body > old_len:
            over.append((title, old_len, body))

    old_sum = sum(r[1] for r in rows)
    new_sum = sum(r[2] for r in rows)
    print(f'{"[预演] " if dry else ""}{len(rows)} 张，{old_sum} -> {new_sum} 字，压缩 {100 * (1 - new_sum / old_sum):.0f}%')

    if long1:
        print('一句话概括超过 40 字:', len(long1))
        for t, n, s in long1:
            print(f'  {t} ({n}字) {s}')
    if over:
        print('正文变长:', len(over))
        for t, o, n in over:
            print(f'  {t}: {o} -> {n} (+{n - o})')

    if dry:
        return
    for r in rows:
        open(r[4], 'wb').write(r[3].encode('utf-8'))
    print('已写入')


if __name__ == '__main__':
    main('--dry-run' in sys.argv)
