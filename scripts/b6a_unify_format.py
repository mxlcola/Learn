def tidy(body):
    """要点统一用 * ；只有真步骤才保留「怎么做」标题。"""
    lines = body.split('\n')
    out, heading = [], ''
    for i, ln in enumerate(lines):
        if ln.startswith('!! '):
            heading = ln
            if ln == '!! 怎么做':
                nxt = next((x for x in lines[i + 1:] if x.strip()), '')
                if not nxt.startswith('#'):
                    heading = ''
                    continue
            out.append(ln)
            continue
        if heading == '!! 要点' and ln.startswith('# '):
            ln = '* ' + ln[2:]
        out.append(ln)
    return '\n'.join(out)


def parse(raw):
    m = re.search(r'\r?\n\r?\n', raw)
    crlf = raw.count('\r\n')
    nl = '\r\n' if crlf > raw.count('\n') - crlf else '\n'
    if not m:
        return nl, raw, ''
    return nl, raw[:m.start()], raw[m.end():]


