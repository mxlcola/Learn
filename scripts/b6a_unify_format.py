def main(dry):
    titles = {f[:-4] for f in os.listdir(TIDDLER_DIR) if f.endswith('.tid')}
    order = [l.strip() for l in open('D:/tmp/b6_1.txt', encoding='utf-8') if l.strip()]

    # 断链检查
    broken = []
    for t, body in BATCH.items():
        for L in re.findall(r'\[\[([^\]|]+)(?:\|[^\]]*)?\]\]', body):
            if L not in titles and L not in broken:
                broken.append(L)

    rows, problems = [], []
    for title in order:
        if title not in BATCH:
            problems.append(f'未改写：{title}')
            continue
        path = os.path.join(TIDDLER_DIR, title + '.tid')
        raw = open(path, 'rb').read().decode('utf-8')
        nl, head, old = parse(raw)
        body = tidy(BATCH[title].strip('\n'))
        base = ORIG_LEN.get(title, len(old))
        final = body.replace('\n', nl)
        out = head + nl + nl + final + nl
        rows.append((title, base, len(final), out, path, head))

        first = body.split('\n')[0]
        if not first.startswith('一句话概括：'):
            problems.append(f'缺一句话概括：{title}')
        else:
            n = len(first) - len('一句话概括：')
            if n > 40:
                problems.append(f'概括 {n} 字超 40：{title}')
        if not re.search(r'(?m)^关联：', body):
            problems.append(f'缺关联行：{title}')
        if body.count('!!') > 2:
            problems.append(f'小标题仍 >2：{title}')
        if len(final) > base:
            problems.append(f'正文变长 {base}->{len(final)}：{title}')
        plain = re.sub(r'\[\[[^\]]*\]\]', '', body)
        if '减脂' in plain:
            problems.append(f'正文仍有“减脂”：{title}')
        rel = re.search(r'(?m)^关联：(.*)$', body)
        if rel:
            links = re.findall(r'\[\[([^\]|]+)(?:\|[^\]]*)?\]\]', rel.group(1))
            if len(links) > 5:
                problems.append(f'关联超过 5 个（{len(links)}）：{title}')
            if len(set(links)) != len(links):
                problems.append(f'关联有重复：{title}')

    old_sum = sum(r[1] for r in rows)
    new_sum = sum(r[2] for r in rows)
    print(f'{"[预演] " if dry else ""}处理 {len(rows)} 张，正文 {old_sum} -> {new_sum} 字'
          f'（{"-" if new_sum <= old_sum else "+"}{abs(new_sum - old_sum)}，{100 * (1 - new_sum / old_sum):+.1f}%）')
    print('断链:', broken or '无')
    for p in problems:
        print(' !', p)
    if dry:
        return
    for r in rows:
        open(r[4], 'wb').write(r[3].encode('utf-8'))
    print('已写入', len(rows), '个文件')


if __name__ == '__main__':
    main('--dry-run' in sys.argv)
