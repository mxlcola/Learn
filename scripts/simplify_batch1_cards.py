def parse(raw):
    nl = '\r\n' if '\r\n' in raw else '\n'
    m = re.search(r'\r?\n\r?\n', raw)
    if not m:
        return nl, raw, ''
    return nl, raw[:m.start()], raw[m.end():]


def content_len(text):
    """去掉空白与结构标记后的正文字数，用于和原文比对。"""
    t = re.sub(r'\[\[([^\]|]+)(?:\|[^\]]*)?\]\]', r'\1', text)
    t = re.sub(r'!!\s*', '', t)
    t = re.sub(r'^\*\s*', '', t, flags=re.M)
    t = re.sub(r'^#\s*', '', t, flags=re.M)
    return len(re.sub(r'\s', '', t))


def main(dry):
    titles = {f[:-4] for f in os.listdir(TIDDLER_DIR) if f.endswith('.tid')}
    problems = []

    for t, body in BATCH.items():
        for L in re.findall(r'\[\[([^\]|]+)(?:\|[^\]]*)?\]\]', body):
            if L not in titles:
                problems.append(f'断链 {t} -> {L}')
        n = len(re.findall(r'\[\[', body))
        if n > 5:
            problems.append(f'链接超 5 个 {t} ({n})')
        first = body.splitlines()[0]
        s = first.replace('一句话概括：', '')
        if not first.startswith('一句话概括：'):
            problems.append(f'缺概括 {t}')
        elif len(s) > 40:
            problems.append(f'概括超 40 字 {t} ({len(s)})')
        if '\n\n关联：' not in body:
            problems.append(f'缺关联行 {t}')

    rows = []
    for title, body in BATCH.items():
        path = os.path.join(TIDDLER_DIR, title + '.tid')
        if not os.path.exists(path):
            print('跳过', title)
            continue
        raw = open(path, 'rb').read().decode('utf-8')
        nl, head, old = parse(raw)
        new = body.strip('\n').replace('\n', nl) + nl
        out = head + nl + nl + new
        rows.append((title, content_len(old), content_len(new), len(old), len(new), out, path, head))

    for r in rows:
        if r[2] > r[1]:
            problems.append(f'正文变长 {r[0]}: {r[1]} -> {r[2]}')

    old_sum = sum(r[1] for r in rows)
    new_sum = sum(r[2] for r in rows)
    cnt = len(BATCH)
    print(f'{"[预演] " if dry else ""}{len(rows)}/{cnt} 张，正文字符 {old_sum} -> {new_sum} '
          f'({100 * (new_sum - old_sum) / old_sum:+.0f}%)')
    for p in problems:
        print('  ⚠', p)
    if problems:
        print(f'共 {len(problems)} 处问题')
    if dry:
        for r in rows[:2]:
            print('\n' + '=' * 20, r[0])
            print(r[5])
        return
    for r in rows:
        open(r[6], 'wb').write(r[5].encode('utf-8'))
    print('写入完成')


if __name__ == '__main__':
    main('--dry-run' in sys.argv)
