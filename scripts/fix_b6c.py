def parse(raw):
    """返回 (行尾, 头部, 正文)。头部与正文之间可能是空行、CR、CRLF 混合。"""
    nl = '\r\n' if '\r\n' in raw else '\n'
    m = re.search(r'\r?\n\r?\n', raw)
    if not m:
        return nl, raw, ''
    return nl, raw[:m.start()], raw[m.end():]


def fix_bullets(body):
    """统一列表符号：除「!! 怎么做」保留有序 # 外，其余一律用 *。"""
    out = []
    cur = ''
    for line in body.split('\n'):
        if line.startswith('!! '):
            cur = line
        elif not cur.startswith('!! 怎么做') and line.startswith('# '):
            # 只有「怎么做」保留有序 #；其余（要点、并列条目）统一用 *
            line = '* ' + line[2:]
        out.append(line)
    return '\n'.join(out)


def norm(s):
    return re.sub(r'\r\n?', '\n', s)


def body_stats(s):
    s = norm(s)
    lines = [l for l in s.splitlines() if l.strip()]
    heads = [l for l in lines if l.startswith('!! ')]
    return len(s), heads


