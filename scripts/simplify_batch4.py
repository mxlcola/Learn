LINK_RE = re.compile(r'\[\[([^\]|]+)(?:\|[^\]]*)?\]\]')


def parse(raw):
    nl = '\r\n' if '\r\n' in raw else '\n'
    m = re.search(r'\r?\n\r?\n', raw)
    if not m:
        return nl, raw, ''
    return nl, raw[:m.start()], raw[m.end():]


def main(dry):
    titles = {f[:-4] for f in os.listdir(TIDDLER_DIR) if f.endswith('.tid')}

    # 断链检查
    missing = []
    for t, body in BATCH.items():
        for L in LINK_RE.findall(body):
            if L not in titles and L not in missing:
                missing.append(L)
    print('断链:', missing or '无')

    for t, body in BATCH.items():
        links = LINK_RE.findall(body)
        if len(links) > 5:
            print(f'  链接超 5 个({len(links)}): {t}')
        if len(set(links)) != len(links):
            print(f'  链接重复: {t} {links}')

    rows = []
    for title, body in BATCH.items():
        path = os.path.join(TIDDLER_DIR, title + '.tid')
        if not os.path.exists(path):
            print('跳过(文件不存在)', title)
            continue
        raw = open(path, 'rb').read().decode('utf-8')
        nl, head, old = parse(raw)
        new = body.strip('\n').replace('\n', nl) + nl
        out = head + nl + nl + new
        rows.append((title, len(old), len(new), out, old, new, path))

    old_sum = sum(r[1] for r in rows)
    new_sum = sum(r[2] for r in rows)
    print(f'{"[预演] " if dry else ""}{len(rows)} 张，{old_sum} -> {new_sum} 字，'
          f'压缩 {100 * (1 - new_sum / old_sum):.0f}%')

    over = [r for r in rows if r[2] > r[1]]
    if over:
        print('字数超标:')
        for r in over:
            print(f'  {r[0]}: {r[1]} -> {r[2]} (+{r[2] - r[1]})')
    if dry:
        for r in rows[:2]:
            print('\n' + '=' * 20, r[0])
            print(r[3])
        return

    for r in rows:
        open(r[6], 'wb').write(r[3].encode('utf-8'))

    print('已写入', len(rows), '个文件')


if __name__ == '__main__':
    main('--dry-run' in sys.argv)
