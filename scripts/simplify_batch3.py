def parse(raw):
    nl = '\r\n' if '\r\n' in raw else '\n'
    m = re.search(r'\r?\n\r?\n', raw)
    if not m:
        return nl, raw, ''
    return nl, raw[:m.start()], raw[m.end():]


def body_chars(s):
    """正文字数：去掉空白后的字符数，用于新旧对比。"""
    return len(re.sub(r'\s', '', s))


def head_version(path):
    """取 git 中的上一版原文，避免重复运行时把自己的改写当成基线。"""
    rel = 'tiddlers/' + os.path.basename(path)
    r = subprocess.run(['git', 'show', 'HEAD:' + rel], cwd=BASE, capture_output=True)
    if r.returncode == 0 and r.stdout:
        return r.stdout.decode('utf-8')
    return None


def main(dry):
    with open(LIST_FILE, 'r', encoding='utf-8') as f:
        titles = [t.strip() for t in f if t.strip()]

    existing = {f[:-4] for f in os.listdir(TIDDLER_DIR) if f.endswith('.tid')}

    bad_links = []
    for t, body in BATCH.items():
        for L in re.findall(r'\[\[([^\]|]+)(?:\|[^\]]*)?\]\]', body):
            if L not in existing:
                bad_links.append((t, L))
    if bad_links:
        print('断链:', bad_links)

    rows, skipped = [], []
    for title in titles:
        if title not in BATCH:
            skipped.append(title + '（未提供改写稿）')
            continue
        path = os.path.join(TIDDLER_DIR, title + '.tid')
        if not os.path.exists(path):
            skipped.append(title + '（文件不存在）')
            continue
        raw = open(path, 'rb').read().decode('utf-8')
        nl, head, old = parse(raw)
        base = head_version(path)
        if base:
            old = parse(base)[2]
        body = BATCH[title]
        out = head + nl + nl + body.strip('\n').replace('\n', nl) + nl
        rows.append((title, body_chars(old), body_chars(body), out, path))

    extra = [t for t in BATCH if t not in titles]
    if extra:
        print('BATCH 中有、清单中没有:', extra)

    o = sum(r[1] for r in rows)
    n = sum(r[2] for r in rows)
    print(f'{"[预演] " if dry else ""}{len(rows)} 张，正文 {o} -> {n} 字，变化 {100 * (n - o) / o:+.0f}%')
    over = [(r[0], r[1], r[2]) for r in rows if r[2] > r[1]]
    if over:
        print('超出原字数:', over)
    if skipped:
        print('跳过:', skipped)

    if dry:
        for r in rows:
            flag = '!' if r[2] > r[1] else ' '
            print(f'{flag} {r[0]}: {r[1]} -> {r[2]}')
        for r in rows[:1]:
            print('\n' + '=' * 20, r[0])
            print(r[3])
        return
    for r in rows:
        open(r[4], 'wb').write(r[3].encode('utf-8'))


if __name__ == '__main__':
    main('--dry-run' in sys.argv)
