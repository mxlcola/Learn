def fix_heads(title, body):
    mapping = HEAD_FIX.get(title)
    if not mapping:
        return body
    out = []
    for line in body.split('\n'):
        m = re.match(r'^!!\s+(\S.*)$', line)
        if m and m.group(1).strip() in mapping:
            new = mapping[m.group(1).strip()]
            if new:
                out.append('!! ' + new)
            continue
        out.append(line)
    text = '\n'.join(out)
    return re.sub(r'\n{3,}', '\n\n', text).strip('\n') + '\n'


def parse(raw):
    nl = '\r\n' if '\r\n' in raw else '\n'
    m = re.search(r'\r?\n\r?\n', raw)
    if not m:
        return nl, raw, ''
    return nl, raw[:m.start()], raw[m.end():]


def check(title, old, new, have):
    errs = []
    old_links = LINK_RE.findall(old)
    new_links = LINK_RE.findall(new)

    broken = [L for L in new_links if L not in have]
    if broken:
        errs.append('断链 %s' % broken)

    lost = [L for L in old_links if L not in new_links]
    if lost:
        errs.append('丢失原有链接 %s' % lost)

    heads = re.findall(r'(?m)^!!\s+\S.*$', new)
    if len(heads) > 2:
        errs.append('小标题 %d 个 %s' % (len(heads), heads))

    if len(new.strip()) > len(old.strip()):
        errs.append('正文变长 %d -> %d' % (len(old.strip()), len(new.strip())))

    m = re.match(r'一句话概括：(.+)', new.strip())
    if not m:
        errs.append('缺一句话概括')
    else:
        line = m.group(1).split('\n')[0].strip()
        if len(line) > 40:
            errs.append('概括 %d 字过长：%s' % (len(line), line))

    rel = [l for l in new.split('\n') if l.startswith('关联：')]
    if len(rel) != 1:
        errs.append('关联行 %d 条' % len(rel))
    else:
        items = [x for x in re.split(r'、', rel[0][3:].strip()) if x]
        names = [LINK_RE.findall(x) for x in items]
        if any(len(n) != 1 for n in names):
            errs.append('关联行含非链接项 %s' % items)
        flat = [n[0] for n in names if n]
        if len(flat) != len(set(flat)):
            errs.append('关联行有重复 %s' % flat)
        if len(flat) > 5:
            errs.append('关联 %d 个 > 5' % len(flat))

    prose = LINK_RE.sub('', new)
    if '减脂' in prose:
        errs.append('正文残留“减脂”：%s' % re.findall(r'.{0,8}减脂.{0,8}', prose))

    return errs


